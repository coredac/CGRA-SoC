static void init_test(void) {
  volatile uint8_t *output = (volatile uint8_t *)(uintptr_t)AES_AUTO_CIPHERTEXT_ADDRESS;
  volatile uint32_t *completion = (volatile uint32_t *)(uintptr_t)AES_AUTO_COMPLETION_ADDRESS;
  for (int i = 0; i < DIM; ++i) {
    for (int j = 0; j < DIM; ++j) {
      B[i][j] = i == j ? (elem_t)1 : (elem_t)0;
    }
  }
  for (unsigned i = 0; i < CGRA_BYTES; ++i) {
    output[i] = 0;
  }
  root_completion = 0;
  *completion = 0;
  __asm__ volatile("fence rw, rw" ::: "memory");
}

static void preload_b(void) {
  gemmini_flush(0);
  gemmini_config_ld(DIM * sizeof(elem_t));
  gemmini_mvin(B, B_ROW);
  gemmini_fence();
}

static void configure_cgra(void) {
  load_relu4x4_config_fast();
  cgra_link_configure(RELU4X4_FAST_LAUNCH_PACKET_COUNT);
  for (unsigned i = 0; i < RELU4X4_FAST_LAUNCH_PACKET_COUNT; ++i) {
    cgra_link_queue(RELU4X4_FAST_LAUNCH_PACKETS[i]);
  }
}

static int configure_gemmini(void) {
  if (gemmini_job_begin(GEMMINI_COMMAND_COUNT) != 0) {
    return 1;
  }
  gemmini_config_ex(WEIGHT_STATIONARY, NO_ACTIVATION, 0);
  gemmini_config_st(DIM * sizeof(acc_t));
  gemmini_preload(B_ROW, ACC_WRITE_ADDR);
  gemmini_compute_preloaded(A_ROW, GARBAGE_ADDR);
  gemmini_extended_mvout_spad(PUBLICATION_ROW, GEMMINI_ROW_STRIDE, ACC_FULL_WIDTH_ADDR, DIM, PUBLICATION_ROWS);
  return 0;
}

static int verify_result(cgra_link_result_t result) { return result.status != AUTO_LINK_STATUS_SUCCESS || result.detail != 0 || result.data != 0; }

static int verify_output(void) {
  const volatile uint8_t *output = (const volatile uint8_t *)(uintptr_t)AES_AUTO_CIPHERTEXT_ADDRESS;
  const volatile uint32_t *completion = (const volatile uint32_t *)(uintptr_t)AES_AUTO_COMPLETION_ADDRESS;
  __asm__ volatile("fence rw, rw" ::: "memory");
  if (root_completion != 1 || *completion != 1) {
    return 1;
  }
  for (unsigned i = 0; i < CGRA_BYTES; ++i) {
    if (output[i] != EXPECTED[i]) {
      return 1;
    }
  }
  return 0;
}

int main(void) {
  init_test();
  preload_b();
  configure_cgra();
  if (configure_gemmini() != 0) {
    printf("AES + Gemmini + CGRA + AES Auto: FAIL\n");
    return 1;
  }
  aes_job_submit(ENCRYPTED_A, AES_INPUT_BYTES, (void *)(uintptr_t)GEMMINI_EXT_SPM_BASE, &root_completion, ROOT_KEY, false);

  const cgra_link_result_t gemmini = cgra_link_wait();
  const cgra_link_result_t cgra = cgra_link_wait();
  const cgra_link_result_t aes = cgra_link_wait();
  if (verify_result(gemmini) != 0 || verify_result(cgra) != 0 || verify_result(aes) != 0 || verify_output() != 0) {
    printf("AES + Gemmini + CGRA + AES Auto: FAIL\n");
    return 1;
  }
  printf("AES + Gemmini + CGRA + AES Auto: PASS\n");
  return 0;
}
