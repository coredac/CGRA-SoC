#!/usr/bin/env python3
"""Generate synthetic multi-head Attention inputs and an exact integer reference."""

import argparse
import random
from pathlib import Path

from attention_data import probabilities

ROOT = Path(__file__).resolve().parents[1]
WIDTH = 64
TILE_ROWS = 16


def matrix(rng, rows, columns, low, high):
    return [[rng.randrange(low, high) for _ in range(columns)] for _ in range(rows)]


def matmul(left, right):
    columns = list(zip(*right))
    return [
        [sum(a * b for a, b in zip(row, column)) for column in columns] for row in left
    ]


def quantize(values, bias):
    return [
        [min(127, max(-128, value + offset)) for value, offset in zip(row, bias)]
        for row in values
    ]


def flatten(rows):
    return [value for row in rows for value in row]


def reference(heads, length):
    hidden = heads * WIDTH
    rng = random.Random(0)
    source = matrix(rng, length, hidden, -2, 3)
    weights = [
        [matrix(rng, hidden, WIDTH, -1, 2) for _ in range(heads)] for _ in range(3)
    ]
    biases = [matrix(rng, heads, WIDTH, -5, 6) for _ in range(3)]
    output_weight = matrix(rng, hidden, hidden, -1, 2)
    output_bias = [rng.randrange(-5, 6) for _ in range(hidden)]
    concat = [[] for _ in range(length)]
    for head in range(heads):
        query, key, value = [
            quantize(matmul(source, weight[head]), bias[head])
            for weight, bias in zip(weights, biases)
        ]
        scores = matmul(query, list(zip(*key)))
        probability = [probabilities(row, index) for index, row in enumerate(scores)]
        result = quantize(matmul(probability, value), [0] * WIDTH)
        for row, values in zip(concat, result):
            row.extend(values)
    output = quantize(matmul(concat, output_weight), output_bias)
    return [
        ("x", "int8_t", flatten(source)),
        *[
            (
                f"w{name}",
                "int8_t",
                [value for head in weight for value in flatten(head)],
            )
            for name, weight in zip("qkv", weights)
        ],
        *[
            (f"b{name}", "int32_t", flatten(value))
            for name, value in zip("qkv", biases)
        ],
        ("wo", "int8_t", flatten(output_weight)),
        ("bo", "int32_t", output_bias),
        ("concat_expected", "int8_t", flatten(concat)),
        ("expected", "int8_t", flatten(output)),
    ]


def header(heads, length, tensors):
    lines = [
        "// Generated by scripts/mha_data.py. Do not edit.",
        "#ifndef MHA_DATA_H",
        "#define MHA_DATA_H",
        "#include <stdint.h>",
        f"enum {{ MHA_N = {length}, MHA_D = {WIDTH}, MHA_HEADS = {heads}, MHA_HIDDEN = {heads * WIDTH}, MHA_TILE_ROWS = {TILE_ROWS} }};",
    ]
    for name, kind, values in tensors:
        lines.append(
            f"static const {kind} mha_{name}[{len(values)}] __attribute__((aligned(32))) = {{"
        )
        lines.extend(
            "  " + ", ".join(map(str, values[start : start + 32])) + ","
            for start in range(0, len(values), 32)
        )
        lines.append("};")
    lines.extend(["#endif", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--heads",
        type=int,
        default=2,
        help="Use 2 for bring-up or 12 for hidden width 768",
    )
    parser.add_argument(
        "--length",
        type=int,
        default=128,
        help="Sequence length: 64 or 128 for the current SPM layout",
    )
    parser.add_argument(
        "--output", type=Path, default=ROOT / "tests/generated/mha_data.h"
    )
    args = parser.parse_args()
    tensors = reference(args.heads, args.length)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(header(args.heads, args.length, tensors), encoding="utf-8")
    print(f"Generated {args.output}: heads={args.heads}, N={args.length}, d={WIDTH}")


if __name__ == "__main__":
    main()
