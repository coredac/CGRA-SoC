#!/usr/bin/env python3
"""Generate exhaustive INT8 GELU expectations from the block host model."""

import argparse
from pathlib import Path

from block_math import gelu

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output", type=Path, default=ROOT / "tests/generated/gelu_data.h"
    )
    args = parser.parse_args()
    expected, _ = gelu([list(range(-128, 128))])
    args.output.parent.mkdir(parents=True, exist_ok=True)
    with args.output.open("w", encoding="utf-8") as stream:
        stream.write("// Generated by scripts/gelu_data.py. Do not edit.\n")
        stream.write("#ifndef GELU_DATA_H\n#define GELU_DATA_H\n#include <stdint.h>\n")
        stream.write("static const int8_t gelu_expected[256] = {\n")
        for start in range(0, 256, 32):
            stream.write(
                "  " + ", ".join(map(str, expected[0][start : start + 32])) + ",\n"
            )
        stream.write("};\n#endif\n")
    print(f"Generated {args.output}")


if __name__ == "__main__":
    main()
