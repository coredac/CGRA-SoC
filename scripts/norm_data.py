#!/usr/bin/env python3
"""Generate maximum-layout LayerNorm inputs and host Q4 expectations."""

import argparse
import random
from pathlib import Path

from block_math import layernorm

ROOT = Path(__file__).resolve().parents[1]
ROWS, WIDTH, RUNS = 16, 768, 2


def fixture(run):
    rows = []
    for row in range(ROWS):
        rng = random.Random(42 + run * ROWS + row)
        cases = (
            [rng.randrange(-128, 128) for _ in range(WIDTH)],
            [-37 + run * 19 + row] * WIDTH,
            [-128 if (index + run + row) % 2 else 127 for index in range(WIDTH)],
            [-3 + run * 5 + (index + row) % 2 for index in range(WIDTH)],
        )
        rows.append(cases[(row + run) % len(cases)])
    return rows


def cases():
    gamma = [(-96, 0, 32, 64, 96)[index % 5] for index in range(WIDTH)]
    beta = [(index % 7 - 3) * 8 for index in range(WIDTH)]
    fixtures = []
    for run in range(RUNS):
        source = fixture(run)
        expected, clipped, stats = layernorm(source, gamma, beta)
        fixtures.append((source, expected, clipped, stats))
    return gamma, beta, fixtures


def header(gamma, beta, fixtures):
    yield "// Generated by scripts/norm_data.py. Do not edit.\n"
    yield "#ifndef NORM_DATA_H\n#define NORM_DATA_H\n#include <stdint.h>\n"
    yield f"enum {{ NORM_ROWS = {ROWS}, NORM_WIDTH = {WIDTH}, NORM_RUNS = {RUNS} }};\n"
    for name, values in (("gamma", gamma), ("beta", beta)):
        yield f"static const int32_t norm_{name}[NORM_WIDTH] __attribute__((aligned(64))) = {{\n"
        for start in range(0, len(values), 32):
            yield "  " + ", ".join(map(str, values[start : start + 32])) + ",\n"
        yield "};\n"
    for index, name in enumerate(("input", "expected")):
        yield f"static const int8_t norm_{name}[NORM_RUNS][NORM_ROWS * NORM_WIDTH] __attribute__((aligned(64))) = {{\n"
        for fixture_data in fixtures:
            yield " {\n"
            for row in fixture_data[index]:
                for start in range(0, len(row), 32):
                    yield "  " + ", ".join(map(str, row[start : start + 32])) + ",\n"
            yield " },\n"
        yield "};\n"
    yield "#endif\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output", type=Path, default=ROOT / "tests/generated/norm_data.h"
    )
    args = parser.parse_args()
    gamma, beta, fixtures = cases()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    with args.output.open("w", encoding="utf-8") as stream:
        stream.writelines(header(gamma, beta, fixtures))
    for run, (_, expected, clipped, stats) in enumerate(fixtures):
        print(
            f"Norm run={run} rows={len(expected)} width={WIDTH} outputs={ROWS * WIDTH} clipped={clipped} max_squares={max(row[2] for row in stats)}"
        )
    print(f"Generated {args.output}")


if __name__ == "__main__":
    main()
