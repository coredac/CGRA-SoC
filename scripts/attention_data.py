#!/usr/bin/env python3
"""Generate synthetic causal attention inputs and their integer reference."""

import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def tensor(rows, columns, seed):
    return [
        ((row + seed) * (column + 3) + row * row + seed * column * column) % 17 - 8
        for row in range(rows)
        for column in range(columns)
    ]


def probabilities(scores, row):
    maximum = max(scores[: row + 1])
    exponents = []
    for value in scores[: row + 1]:
        # Q and K have scale 1/8; d=64 gives score scale 1/512.
        distance = min((maximum - value) >> 1, 4096)
        shift = (distance * 370) >> 16
        polynomial = 346 - distance + 177 * shift
        exponents.append((polynomial * polynomial + 62885) >> (shift + 2))
    total = sum(exponents)
    return [(value * 127 + total // 2) // total for value in exponents] + [0] * (
        len(scores) - row - 1
    )


def reference(length, width):
    query, key, value = [tensor(length, width, seed) for seed in (1, 3, 5)]
    result = []
    for row in range(length):
        scores = [
            sum(query[row * width + k] * key[column * width + k] for k in range(width))
            for column in range(length)
        ]
        weights = probabilities(scores, row)
        result.extend(
            sum(weights[k] * value[k * width + column] for k in range(length))
            for column in range(width)
        )
    return query, key, value, result


def header(length, width, tile_rows, tensors):
    lines = [
        "// Generated by scripts/attention_data.py.",
        "#ifndef ATTENTION_DATA_H",
        "#define ATTENTION_DATA_H",
        "#include <stdint.h>",
        f"enum {{ ATTENTION_N = {length}, ATTENTION_D = {width}, ATTENTION_TILE_ROWS = {tile_rows} }};",
    ]
    for name, kind, values in zip(
        ("attention_q", "attention_k", "attention_v", "attention_expected"),
        ("int8_t", "int8_t", "int8_t", "int32_t"),
        tensors,
    ):
        lines.append(
            f"static const {kind} {name}[{len(values)}] __attribute__((aligned(32))) = {{"
        )
        lines.extend(
            "  " + ", ".join(map(str, values[start : start + 32])) + ","
            for start in range(0, len(values), 32)
        )
        lines.append("};")
    lines.extend(["#endif", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--length",
        type=int,
        default=128,
        help="Sequence length, a multiple of 64 up to 128 for the current SPM layout",
    )
    parser.add_argument(
        "--tile-rows",
        type=int,
        default=16,
        help="Query rows per tile, at most 16; padded native Q/K and publication regions must fit SPM",
    )
    parser.add_argument(
        "--output", type=Path, default=ROOT / "tests/generated/attention_data.h"
    )
    args = parser.parse_args()
    width = 64
    tensors = reference(args.length, width)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(
        header(args.length, width, args.tile_rows, tensors), encoding="utf-8"
    )
    print(f"Generated {args.output}: {args.length}x{width}, tile rows {args.tile_rows}")


if __name__ == "__main__":
    main()
