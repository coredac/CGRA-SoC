#!/usr/bin/env python3
"""Generate dense native GEMM regression inputs and independent integer outputs."""

import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ROWS, COLS, CHUNK, MAX_K = 16, 64, 768, 3072


def fixture(width, trial, extreme):
    seed = 1 + trial

    def sample():
        nonlocal seed
        seed = (seed * 1664525 + 1013904223) & 0xFFFFFFFF
        return (seed >> 24) - 128

    inputs = [-128 if extreme else sample() for _ in range(ROWS * width)]
    weights = [
        (127 if column % 2 else -128) if extreme else sample()
        for _ in range(width)
        for column in range(COLS)
    ]
    bias = [(column - 32) * 37 + trial for column in range(COLS)]
    columns = [weights[column::COLS] for column in range(COLS)]
    # Python integers retain the full dot product, independently of K chunking.
    expected = [
        bias[column] + sum(a * b for a, b in zip(inputs[row : row + width], taps))
        for row in range(0, len(inputs), width)
        for column, taps in enumerate(columns)
    ]
    return width, trial, extreme, inputs, weights, bias, expected


def cases():
    return [
        fixture(width, endpoint * 3 + index, extreme)
        for endpoint in range(2)
        for index, (width, extreme) in enumerate(
            ((CHUNK, False), (MAX_K, False), (MAX_K, True))
        )
    ]


def header(fixtures):
    yield "// Generated by scripts/mlp_data.py. Do not edit.\n"
    yield "#ifndef MLP_DATA_H\n#define MLP_DATA_H\n#include <stdint.h>\n"
    yield f"enum {{ MLP_ROWS = {ROWS}, MLP_COLS = {COLS}, MLP_CHUNK = {CHUNK} }};\n"
    yield "typedef struct { unsigned width, trial, extreme; const int8_t *input, *weight; const int32_t *bias, *expected; } mlp_case_t;\n"
    fields = (
        ("input", "int8_t"),
        ("weight", "int8_t"),
        ("bias", "int32_t"),
        ("expected", "int32_t"),
    )
    for index, (_, _, _, *arrays) in enumerate(fixtures):
        for (name, kind), values in zip(fields, arrays):
            yield f"static const {kind} mlp_{name}{index}[{len(values)}] __attribute__((aligned(64))) = {{\n"
            for start in range(0, len(values), 32):
                yield "  " + ", ".join(map(str, values[start : start + 32])) + ",\n"
            yield "};\n"
    yield "static const mlp_case_t mlp_cases[] = {\n"
    for index, (width, trial, extreme, *_) in enumerate(fixtures):
        yield f"  {{{width}, {trial}, {int(extreme)}, mlp_input{index}, mlp_weight{index}, mlp_bias{index}, mlp_expected{index}}},\n"
    yield "};\n#endif\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output", type=Path, default=ROOT / "tests/generated/mlp_data.h"
    )
    args = parser.parse_args()
    fixtures = cases()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    with args.output.open("w", encoding="utf-8") as stream:
        stream.writelines(header(fixtures))
    for width, trial, extreme, *_, expected in fixtures:
        print(
            f"MLP K={width} trial={trial} extreme={int(extreme)} outputs={len(expected)} max_abs={max(map(abs, expected))}"
        )
    print(f"Generated {args.output}")


if __name__ == "__main__":
    main()
