#!/usr/bin/env python3
"""Generate small synthetic graphs and a single-layer integer GCN reference.

Inputs are degree one-hot features with deterministic dense synthetic weights.
Output is INT32 Q15 after normalized sparse aggregation and ReLU, without
requantizing. These fixtures validate arithmetic and scheduling, not accuracy.
"""

import argparse
import hashlib
import json
import math
import random
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
INPUTS, OUTPUTS, SCALE = 64, 128, 32768


def graphs(seed, star_nodes=20):
    rng = random.Random(seed + 1000)
    cases = []
    for index, (name, nodes, active) in enumerate(
        (
            ("ring-chords", 16, 16),
            ("star", star_nodes, star_nodes),
            ("irregular-isolated", 32, 31),
        )
    ):
        neighbors = [set() for _ in range(nodes)]
        if name == "star":
            edges = [(0, node) for node in range(1, nodes)]
        else:
            edges = [(node, (node + 1) % active) for node in range(active)]
            edges.extend(rng.sample(range(active), 2) for _ in range(active))
        for left, right in edges:
            neighbors[left].add(right)
            neighbors[right].add(left)
        cases.append(dict(id=index + 1, name=name, neighbors=neighbors))
    return cases


def weights(seed):
    rng = random.Random(seed)
    return [rng.randrange(-8, 9) for _ in range(INPUTS * OUTPUTS)]


def reference(graph, weight, sign=1):
    neighbors = graph["neighbors"]
    nodes = len(neighbors)
    rows = (nodes + 15) // 16 * 16
    degrees = [len(row) for row in neighbors]
    adjacency = [sorted(row | {index}) for index, row in enumerate(neighbors)]
    sizes = [len(row) for row in adjacency]
    source = [0] * (rows * INPUTS)
    projected = [0] * (rows * OUTPUTS)
    for row, degree in enumerate(degrees):
        source[row * INPUTS + degree] = sign
        projected[row * OUTPUTS : (row + 1) * OUTPUTS] = [
            sign * value for value in weight[degree * OUTPUTS : (degree + 1) * OUTPUTS]
        ]
    rowptr, columns, edge_weights = [0], [], []
    summed, expected, floating = [], [], []
    for row, adjacent in enumerate(adjacency):
        integer = [0] * OUTPUTS
        real = [0.0] * OUTPUTS
        for column in adjacent:
            factor = 1 / math.sqrt(sizes[row] * sizes[column])
            quantized = math.floor(factor * SCALE + 0.5)
            columns.append(column)
            edge_weights.append(quantized)
            for feature in range(OUTPUTS):
                value = projected[column * OUTPUTS + feature]
                integer[feature] += quantized * value
                real[feature] += factor * value
        rowptr.append(len(columns))
        summed.extend(integer)
        expected.extend(max(value, 0) for value in integer)
        floating.extend(max(value, 0.0) for value in real)
    errors = [actual / SCALE - real for actual, real in zip(expected, floating)]
    tensors = {
        "x": ("int8_t", source),
        "rowptr": ("uint32_t", rowptr),
        "col": ("uint32_t", columns),
        "edge_weight": ("int32_t", edge_weights),
        "expected_z": ("int32_t", projected),
        "expected_sum": ("int32_t", summed),
        "expected_y": ("int32_t", expected),
    }
    report = {
        "id": graph["id"],
        "name": graph["name"],
        "nodes": nodes,
        "rows": rows,
        "directed_edges": sum(degrees),
        "edges": len(columns),
        "degree_min": min(degrees),
        "degree_max": max(degrees),
        "degree_mean": sum(degrees) / nodes,
        "outputs": len(expected),
        "accum_max_abs": max(map(abs, summed)),
        "float_error": {
            "max_abs": max(map(abs, errors)),
            "rmse": math.sqrt(sum(error * error for error in errors) / len(errors)),
        },
    }
    return tensors, report


def array_lines(name, kind, values):
    yield f"static const {kind} {name}[{len(values)}] __attribute__((aligned(64))) = {{\n"
    for start in range(0, len(values), 32):
        yield "  " + ", ".join(map(str, values[start : start + 32])) + ",\n"
    yield "};\n"


def header(weight, fixtures, alternates):
    yield "// Generated by scripts/gcn_data.py. Do not edit.\n"
    yield "#ifndef GCN_DATA_H\n#define GCN_DATA_H\n#include <stdint.h>\n"
    yield '#define GCN_DATASET "synthetic-gcn"\n'
    reports = [report for _, report in fixtures]
    yield f"enum {{ GCN_GRAPHS = {len(fixtures)}, GCN_INPUTS = {INPUTS}, GCN_OUTPUTS = {OUTPUTS}, GCN_SCALE = {SCALE}, GCN_MAX_ROWS = {max(item['rows'] for item in reports)}, GCN_MAX_EDGES = {max(item['edges'] for item in reports)} }};\n"
    yield "typedef struct {\n  unsigned id, nodes, rows, edges;\n  const int8_t *x;\n  const uint32_t *rowptr, *col;\n  const int32_t *edge_weight, *expected_z, *expected_sum, *expected_y;\n} gcn_graph_t;\n"
    yield from array_lines("gcn_weight", "int8_t", weight)
    for index, (tensors, _) in enumerate(fixtures):
        for name, (kind, values) in tensors.items():
            if name in ("col", "edge_weight"):
                values = values + [0] * (-len(values) % 4)
            yield from array_lines(f"gcn_{index}_{name}", kind, values)
    yield "static const gcn_graph_t gcn_graphs[GCN_GRAPHS] = {\n"
    for index, (tensors, report) in enumerate(fixtures):
        values = [str(report[key]) for key in ("id", "nodes", "rows", "edges")]
        values.extend(f"gcn_{index}_{name}" for name in tensors)
        yield "  {" + ", ".join(values) + "},\n"
    yield "};\n"
    for index, (tensors, _) in enumerate(alternates):
        for name in ("x", "expected_z", "expected_sum", "expected_y"):
            kind, values = tensors[name]
            yield from array_lines(f"gcn_alt_{index}_{name}", kind, values)
    yield "static const gcn_graph_t gcn_alt_graphs[GCN_GRAPHS] = {\n"
    for index, (tensors, report) in enumerate(alternates):
        values = [str(report[key]) for key in ("id", "nodes", "rows", "edges")]
        values.extend(
            (
                f"gcn_{index}_{name}"
                if name in ("rowptr", "col", "edge_weight")
                else f"gcn_alt_{index}_{name}"
            )
            for name in tensors
        )
        yield "  {" + ", ".join(values) + "},\n"
    yield "};\n#endif\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--star-nodes", type=int, choices=(20, 64), default=20)
    parser.add_argument(
        "--output", type=Path, default=ROOT / "tests/generated/gcn_data.h"
    )
    parser.add_argument("--report", type=Path, required=True)
    args = parser.parse_args()
    weight = weights(args.seed)
    fixtures = [
        reference(graph, weight) for graph in graphs(args.seed, args.star_nodes)
    ]
    alternates = [
        reference(graph, weight, -1) for graph in graphs(args.seed, args.star_nodes)
    ]
    contents = "".join(header(weight, fixtures, alternates))
    report = {
        "dataset": "synthetic-gcn",
        "header_sha256": hashlib.sha256(contents.encode()).hexdigest(),
        "seed": args.seed,
        "inputs": INPUTS,
        "outputs": OUTPUTS,
        "features": "one-hot original degree (before self-loops); zero-padded rows",
        "weights": "synthetic dense INT8 uniform integers [-8,8], no bias; not trained accuracy",
        "normalization": "D^-1/2 (A+I) D^-1/2, positive Q15 rounded nearest; one self-loop per node",
        "output": "INT32 Q15 ReLU after full neighbor reduction, no downshift",
        "graphs": [item for _, item in fixtures],
        "alternate_features": "negative original degree one-hot; shared graph and weights",
    }
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(contents, encoding="utf-8")
    args.report.parent.mkdir(parents=True, exist_ok=True)
    text = json.dumps(report, indent=2)
    args.report.write_text(text + "\n", encoding="utf-8")
    print(text)
    print(f"Generated {args.output}")


if __name__ == "__main__":
    main()
