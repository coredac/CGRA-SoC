#!/usr/bin/env python3
"""Generate runtime fixtures for the Rocket ASIC adapter benchmark."""

import argparse
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts"))
from asic.gpt import fixtures as gpt_fixtures
from asic.vector import fixtures as vector_fixtures
import gcn_data


class Case:
    def __init__(self, name, workload, smoke=False):
        self.name = name
        self.workload = workload
        self.smoke = smoke
        self.words = 0
        self.loads = []
        self.checks = []
        self.jobs = []

    def space(self, count):
        offset = self.words
        self.words += (count + 7) // 8 * 8
        return offset

    def load(self, values):
        offset = self.space(len(values))
        self.loads.append({"offset": offset, "values": list(values)})
        return offset

    def check(self, offset, values):
        self.checks.append({"offset": offset, "values": list(values)})

    def job(self, unit, dst, **fields):
        descriptor = dict.fromkeys(
            "unit operation fused phase count rows edges divisor src0 src1 src2 src3 dst next_job".split(),
            0,
        )
        descriptor.update(unit=unit, dst=dst, divisor=1)
        descriptor.update(fields)
        self.jobs.append(descriptor)


def vector_cases(data):
    rowptr, columns, weights, features, summed, expected = data["arrays"][:6]
    case = Case("gcn-aggregate-relu", "gcn", True)
    inputs = [case.load(values) for values in (rowptr, columns, weights, features)]
    middle = case.space(len(summed))
    output = case.space(len(expected))
    case.job(
        0,
        middle,
        rows=len(rowptr) - 1,
        edges=len(columns),
        src0=inputs[0],
        src1=inputs[1],
        src2=inputs[2],
        src3=inputs[3],
    )
    case.job(1, output, count=len(expected), src0=middle)
    case.check(output, expected)
    result = [case]
    first, activated, main, skip, residual = data["arrays"][6:]
    case = Case("resnet-relu", "resnet")
    source = case.load(first)
    output = case.space(len(activated))
    case.job(1, output, count=len(first), src0=source)
    case.check(output, activated)
    result.append(case)
    case = Case("resnet-add-relu", "resnet", True)
    a, b = case.load(main), case.load(skip)
    middle = case.space(len(main))
    output = case.space(len(residual))
    case.job(1, middle, operation=1, count=len(main), src0=a, src1=b)
    case.job(1, output, count=len(main), src0=middle)
    case.check(output, residual)
    result.append(case)
    return result


def gpt_cases(run):
    inputs = [
        item
        for item in gpt_fixtures()
        if item["name"].startswith(f"run{run}-") and item["phases"] == 1
    ]
    gelu = next(item for item in inputs if item["name"] == f"run{run}-gelu-fused")
    result = []
    for item in inputs:
        name = item["name"].removeprefix(f"run{run}-").removesuffix("-fused")
        if name == "gelu":
            continue
        case = Case(
            "gpt-" + name,
            "gpt",
            name in ("ln1-row0", "softmax-row1", "requant-fc1"),
        )
        source = case.load(item["source"])
        extra = case.load(item["extra"]) if item["extra"] else 0
        beta = case.load(item["beta"]) if item["beta"] else 0
        output = case.space(len(item["expected"]))
        unit = (2, 3, 4)[item["unit"]]
        phases = {2: 7, 3: 3, 4: 1}[unit]
        for phase in range(phases):
            case.job(
                unit,
                output,
                phase=phase,
                count=len(item["source"]),
                rows=item["row"],
                operation=item["operation"],
                divisor=item["divisor"],
                src0=source,
                src1=extra,
                src2=beta,
            )
        case.check(output, item["expected"])
        if name == "requant-fc1":
            activated = case.space(len(gelu["expected"]))
            case.job(4, activated, count=len(gelu["source"]), src0=output)
            case.check(activated, gelu["expected"])
        result.append(case)
    return result


def fixtures():
    vectors = list(vector_fixtures())
    return [vector_cases(vectors[run]) + gpt_cases(run) for run in range(2)]


def array(name, values):
    lines = [f"static const int32_t {name}[] = {{"]
    for first in range(0, len(values), 16):
        lines.append("  " + ", ".join(map(str, values[first : first + 16])) + ",")
    lines.append("};")
    return "\n".join(lines)


def header(inputs):
    text = ["/* Generated by scripts/asic/fixtures.py. Include fixture.h first. */"]
    entries = []
    for index, cases in enumerate(zip(*inputs)):
        first = cases[0]
        name = f"fixture_{index}"
        for kind in ("loads", "checks"):
            segments = getattr(first, kind)
            for segment in range(len(segments)):
                for run, case in enumerate(cases):
                    text.append(
                        array(
                            f"{name}_{kind}_{segment}_{run}",
                            getattr(case, kind)[segment]["values"],
                        )
                    )
            text.append(f"static const fixture_segment_t {name}_{kind}[] = {{")
            for segment, entry in enumerate(segments):
                count = len(entry["values"])
                pointers = ", ".join(
                    f"{name}_{kind}_{segment}_{run}" for run in range(2)
                )
                text.append(f"  {{{entry['offset']}, {count}, {{{pointers}}}}},")
            text.append("};")
        text.append(f"static const asic_job_t {name}_jobs[] = {{")
        for job in first.jobs:
            fields = ", ".join(f".{key} = {value}" for key, value in job.items())
            text.append("  {" + fields + "},")
        text.append("};")
        entries.append(
            f'  {{"{first.name}", "{first.workload}", {int(first.smoke)}, '
            f"{len(first.loads)}, {len(first.checks)}, {len(first.jobs)}, "
            f"{name}_loads, {name}_checks, {name}_jobs}},"
        )
    text.extend(["static const fixture_t fixtures[] = {", *entries, "};"])
    text.append(f"#define FIXTURE_COUNT {len(inputs[0])}u")
    return "\n".join(text) + "\n"


def gcn_header():
    graph = gcn_data.graphs(0)[0]
    weights = gcn_data.weights(0)
    inputs = [
        gcn_data.reference(graph, weights, sign=sign, row_align=64) for sign in (1, -1)
    ]
    tensors, report = inputs[0]
    lines = [
        "/* Generated by scripts/asic/fixtures.py. Do not edit. */\n",
        "#include <stdint.h>\n",
        f"enum {{ GCN_NODES = {report['nodes']}, GCN_EDGES = {report['edges']}, GCN_INNER = 64, GCN_COLUMNS = 128 }};\n",
    ]
    lines.extend(gcn_data.array_lines("gcn_weight", "int8_t", weights))
    for name in ("rowptr", "col", "edge_weight"):
        kind, values = tensors[name]
        values = values + [0] * (-len(values) % 8)
        lines.extend(gcn_data.array_lines(f"gcn_{name}", kind, values))
    for index, (data, _) in enumerate(inputs):
        for name in ("x", "expected_y"):
            kind, values = data[name]
            lines.extend(gcn_data.array_lines(f"gcn_{name}{index}", kind, values))
    lines.append("static const int8_t *const gcn_inputs[] = {gcn_x0, gcn_x1};\n")
    lines.append(
        "static const int32_t *const gcn_expected[] = {gcn_expected_y0, gcn_expected_y1};\n"
    )
    return "".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output", type=Path, default=ROOT / "build/experiments/asic/system"
    )
    args = parser.parse_args()
    inputs = fixtures()
    for first, second in zip(*inputs):
        if first.jobs != second.jobs or first.words > 32768:
            print(f"Invalid paired layout: {first.name}", file=sys.stderr)
            return 1
        for kind in ("loads", "checks"):
            layout = lambda case: [
                (item["offset"], len(item["values"])) for item in getattr(case, kind)
            ]
            if layout(first) != layout(second):
                print(f"Different runtime input layout: {first.name}", file=sys.stderr)
                return 1
    args.output.mkdir(parents=True, exist_ok=True)
    output = args.output / "fixtures.h"
    output.write_text(header(inputs))
    gcn = args.output / "gcn.h"
    gcn.write_text(gcn_header())
    sources = [
        Path(__file__).resolve(),
        ROOT / "scripts/asic/vector.py",
        ROOT / "scripts/asic/gpt.py",
        ROOT / "scripts/gcn_data.py",
        ROOT / "scripts/p1_resnet_data.py",
        ROOT / "scripts/gpt2_data.py",
        ROOT / "scripts/block_math.py",
    ]
    report = {
        "scope": "Reference intermediate tensors for actual Rocket ASIC adapter/DMA tests; not full Gemmini workload execution.",
        "inputs": 2,
        "cases": [
            {
                "name": case.name,
                "workload": case.workload,
                "smoke": case.smoke,
                "jobs": len(case.jobs),
                "local_words": case.words,
                "checked_words": sum(len(item["values"]) for item in case.checks),
            }
            for case in inputs[0]
        ],
        "sha256": {
            str(path.relative_to(ROOT)): hashlib.sha256(path.read_bytes()).hexdigest()
            for path in sources
        },
        "header_sha256": hashlib.sha256(output.read_bytes()).hexdigest(),
        "gcn_header_sha256": hashlib.sha256(gcn.read_bytes()).hexdigest(),
    }
    (args.output / "fixtures.json").write_text(json.dumps(report, indent=2) + "\n")
    print(f"Generated {len(inputs[0])} paired cases: {output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
