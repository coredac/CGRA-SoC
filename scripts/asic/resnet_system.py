#!/usr/bin/env python3
"""Generate raw inputs, weights and final outputs for the ResNet system test."""

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts"))

from block_data import conv
from p1_resnet_data import CASES, reference


def tensors(name="small"):
    rows, columns, inputs, channels = CASES[name]
    base = reference(name)
    original = base["p1_input"]
    changed = [-value for value in original]
    first = conv(
        changed, base["p1_weights1"], rows, columns, inputs, channels, 3, 2, 1, True
    )
    main = conv(
        first, base["p1_weights2"], rows // 2, columns // 2, channels, channels, 3, 1, 1
    )
    skip = conv(
        changed, base["p1_projection"], rows, columns, inputs, channels, 1, 2, 0
    )
    expected = [max(0, left + right) for left, right in zip(main, skip)]
    return {
        "resnet_inputs": ("int8_t", [original, changed]),
        "resnet_weights1": ("int8_t", base["p1_weights1"]),
        "resnet_weights2": ("int8_t", base["p1_weights2"]),
        "resnet_projection": ("int8_t", base["p1_projection"]),
        "resnet_expected": ("int32_t", [base["p1_expected"], expected]),
    }


def header(values, name="small"):
    rows, columns, inputs, channels = CASES[name]
    lines = [
        "/* Generated by scripts/asic/resnet_system.py. Do not edit. */",
        "#ifndef ASIC_RESNET_DATA_H",
        "#define ASIC_RESNET_DATA_H",
        "#include <stdint.h>",
        f"enum {{ RESNET_INPUT_H = {rows}, RESNET_INPUT_W = {columns}, RESNET_INPUT_C = {inputs},",
        f"       RESNET_H = {rows // 2}, RESNET_W = {columns // 2}, RESNET_C = {channels} }};",
    ]
    for name, (kind, data) in values.items():
        matrix = isinstance(data[0], list)
        shape = f"[{len(data)}][{len(data[0])}]" if matrix else f"[{len(data)}]"
        lines.append(
            f"static const {kind} {name}{shape} __attribute__((aligned(64))) = {{"
        )
        for row in data if matrix else [data]:
            if matrix:
                lines.append("  {")
            for start in range(0, len(row), 32):
                lines.append(
                    "    " + ", ".join(map(str, row[start : start + 32])) + ","
                )
            if matrix:
                lines.append("  },")
        lines.append("};")
    lines.extend(["#endif", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--case", choices=CASES, default="small")
    parser.add_argument(
        "--output",
        type=Path,
        default=ROOT / "build/experiments/asic/system/resnet.h",
    )
    args = parser.parse_args()
    values = tensors(args.case)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(header(values, args.case), encoding="utf-8")
    rows, columns, inputs, channels = CASES[args.case]
    print(
        f"Generated {args.output}: two {rows}x{columns}x{inputs} inputs, {rows * columns * channels // 4} final values each"
    )


if __name__ == "__main__":
    main()
