#!/usr/bin/env python3
"""Emit only inputs, weights and final references for the small ASIC GPT system."""

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts"))
import gpt2_data


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output",
        type=Path,
        default=ROOT / "build/experiments/asic/system/gpt.h",
    )
    args = parser.parse_args()
    fixtures = [gpt2_data.reference(2, 2, run=run)[0] for run in range(2)]
    names = {"x", "expected_y", "gamma1", "beta1", "gamma2", "beta2"}
    names.update(
        prefix + name for prefix in ("w", "b") for name in gpt2_data.NAMES.values()
    )
    selected = [
        {key: value for key, value in fixture.items() if key in names}
        for fixture in fixtures
    ]
    args.output.parent.mkdir(parents=True, exist_ok=True)
    content = "".join(gpt2_data.header(2, 2, selected))
    content = content.replace(
        "Generated by scripts/gpt2_data.py", "Generated by scripts/asic/gpt_system.py"
    )
    args.output.write_text(content)
    print(
        f"{args.output}: 2 inputs, 256 final values/input; no reference intermediates"
    )


if __name__ == "__main__":
    main()
