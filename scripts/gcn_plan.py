#!/usr/bin/env python3
"""Describe a fixed CSR graph with existing projection and aggregation kernels.

Topology and Q15 edge weights come from JSON. Feature and dense-weight tensors
remain runtime inputs. This caller emits computation dependencies and padded
host arrays; the SoC compiler chooses placement, storage and execution plans.
"""

import argparse
import json
from pathlib import Path

from kernel_graph import Graph


def validate(graph, dma_bytes):
    if dma_bytes < 4 or dma_bytes & (dma_bytes - 1):
        return "DMA alignment must be a power of two, at least four bytes"
    if any(
        type(graph[name]) is not int or graph[name] <= 0
        for name in ("inputs", "outputs")
    ):
        return "inputs and outputs must be positive integers"
    for name in ("rowptr", "columns", "edge_weights"):
        if not isinstance(graph[name], list) or any(
            type(value) is not int for value in graph[name]
        ):
            return f"{name} must be an integer array"
    rows, columns, weights = graph["rowptr"], graph["columns"], graph["edge_weights"]
    if (
        len(rows) < 2
        or rows[0] != 0
        or rows[-1] != len(columns)
        or len(columns) != len(weights)
    ):
        return "CSR offsets and edge arrays disagree"
    if any(end <= start for start, end in zip(rows, rows[1:])):
        return "the native aggregation kernel requires a nonempty CSR row"
    if any(column < 0 or column >= len(rows) - 1 for column in columns):
        return "CSR neighbor index is outside the graph"
    if any(value < -(2**31) or value >= 2**31 for value in weights):
        return "edge weights must fit INT32"
    return None


def workload(model, padded):
    nodes, inner, width = len(model["rowptr"]) - 1, model["inputs"], model["outputs"]
    graph = Graph("gcn")
    source = graph.tensor("input", nodes, inner, 8)
    weight = graph.tensor("weight", inner, width, 8)
    bias = graph.tensor("bias", 1, width, 32)
    projected = graph.tensor("projected", nodes, width, 32)
    graph.call(
        "projection",
        "gemmini_matrix",
        [source, weight, bias],
        [projected],
        {"m": nodes, "k": inner, "n": width, "transpose_a": 0, "transpose_b": 0},
    )
    results = []
    for node, (start, end) in enumerate(zip(model["rowptr"], model["rowptr"][1:])):
        node_neighbors = graph.tensor(f"neighbors{node}", 1, padded, 32)
        node_weights = graph.tensor(f"weights{node}", 1, padded, 32)
        output = graph.tensor(f"output{node}", 1, width, 32)
        graph.call(
            f"node{node}",
            "gcn",
            [projected, node_neighbors, node_weights],
            [output],
            {"columns": end - start, "row": 0, "stride": "n"},
        )
        results.append(output)
    return graph.emit(results)


def header(graph, padded, dma_bytes):
    nodes = len(graph["rowptr"]) - 1
    text = f"""// Generated by scripts/gcn_plan.py. Do not edit.
#ifndef RUNTIME_GCN_DATA_H
#define RUNTIME_GCN_DATA_H
#include <stdint.h>
enum {{ GCN_NODES = {nodes}, GCN_INPUTS = {graph['inputs']}, GCN_OUTPUTS = {graph['outputs']}, GCN_EDGE_WORDS = {padded}, GCN_ARGUMENTS = {4 + 3 * nodes} }};
"""
    text += f"static const int32_t gcn_bias[GCN_OUTPUTS] __attribute__((aligned({dma_bytes}))) = {{0}};\n"
    degrees = [end - start for start, end in zip(graph["rowptr"], graph["rowptr"][1:])]
    text += f"static const unsigned gcn_degrees[GCN_NODES] = {{{', '.join(map(str, degrees))}}};\n"
    for field, name, kind in (
        ("columns", "neighbors", "uint32_t"),
        ("edge_weights", "edges", "int32_t"),
    ):
        text += f"static const {kind} gcn_{name}[GCN_NODES][GCN_EDGE_WORDS] __attribute__((aligned({dma_bytes}))) = {{\n"
        for start, end in zip(graph["rowptr"], graph["rowptr"][1:]):
            values = graph[field][start:end] + [0] * (padded - (end - start))
            text += "  {" + ", ".join(map(str, values)) + "},\n"
        text += "};\n"
    text += """static void gcn_arguments(uintptr_t *arguments, const int8_t *input, const int8_t *weight, int32_t *output) {
  arguments[0] = (uintptr_t)input;
  arguments[1] = (uintptr_t)weight;
  arguments[2] = (uintptr_t)gcn_bias;
  arguments[3] = 0;
  for (unsigned node = 0; node < GCN_NODES; ++node) {
    arguments[4 + 3 * node] = (uintptr_t)gcn_neighbors[node];
    arguments[5 + 3 * node] = (uintptr_t)gcn_edges[node];
    arguments[6 + 3 * node] = (uintptr_t)(output + node * GCN_OUTPUTS);
  }
}
#endif
"""
    return text


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("graph", type=Path)
    parser.add_argument(
        "--dma-bytes", type=int, required=True, help="target DMA alignment"
    )
    parser.add_argument(
        "--output", type=Path, required=True, help="Taskflow MLIR destination"
    )
    parser.add_argument(
        "--header", type=Path, required=True, help="matching CSR binding header"
    )
    args = parser.parse_args()
    try:
        graph = json.loads(args.graph.read_text())
        error = validate(graph, args.dma_bytes)
        if error:
            parser.error(error)
        largest = max(
            end - start for start, end in zip(graph["rowptr"], graph["rowptr"][1:])
        )
        words = args.dma_bytes // 4
        padded = (largest + words - 1) // words * words
        args.output.write_text(workload(graph, padded))
        args.header.write_text(header(graph, padded, args.dma_bytes))
    except (OSError, ValueError, KeyError, TypeError) as error:
        parser.error(str(error))


if __name__ == "__main__":
    main()
