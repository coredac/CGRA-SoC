#!/usr/bin/env python3
"""Generate projected-block inputs and exact INT32 references."""

import argparse
from pathlib import Path

from block_data import conv

ROOT = Path(__file__).resolve().parents[1]
CASES = {
    "small": (8, 8, 4, 8),
    "medium": (16, 16, 8, 16),
    "spatial": (32, 32, 8, 16),
    "large": (32, 32, 16, 32),
}


def reference(name):
    rows, columns, inputs, channels = CASES[name]
    source = [
        (row * 7 + column * 3 + channel * 2) % 7 - 3
        for row in range(rows)
        for column in range(columns)
        for channel in range(inputs)
    ]
    first = [
        (y * 3 + x * 2 + channel + out * 2) % 5 - 2
        for y in range(3)
        for x in range(3)
        for channel in range(inputs)
        for out in range(channels)
    ]
    second = [
        (y + x * 3 + channel * 2 + out) % 3 - 1
        for y in range(3)
        for x in range(3)
        for channel in range(channels)
        for out in range(channels)
    ]
    projection = [
        (channel * 3 + out) % 5 - 2
        for channel in range(inputs)
        for out in range(channels)
    ]
    activated = conv(source, first, rows, columns, inputs, channels, 3, 2, 1, True)
    main = conv(activated, second, rows // 2, columns // 2, channels, channels, 3, 1, 1)
    skip = conv(source, projection, rows, columns, inputs, channels, 1, 2, 0)
    expected = [max(0, a + b) for a, b in zip(main, skip)]
    return {
        "p1_input": source,
        "p1_weights1": first,
        "p1_weights2": second,
        "p1_projection": projection,
        "p1_expected": expected,
    }


def header(name, tensors):
    rows, columns, inputs, channels = CASES[name]
    lines = [
        "/* Generated by scripts/p1_resnet_data.py. Do not edit. */",
        "#ifndef P1_RESNET_DATA_H",
        "#define P1_RESNET_DATA_H",
        "",
        "#include <stdint.h>",
        "",
        "enum {",
        f"  INPUT_H = {rows}, INPUT_W = {columns}, INPUT_CHANNELS = {inputs},",
        f"  HEIGHT = {rows // 2}, WIDTH = {columns // 2}, CHANNELS = {channels},",
        "  KERNEL = 3, STRIDE = 2, PADDING = 1,",
        "};",
        "",
    ]
    for symbol, values in tensors.items():
        kind = "int32_t" if symbol == "p1_expected" else "int8_t"
        lines.append(
            f"static const {kind} {symbol}[{len(values)}] __attribute__((aligned(64))) = {{"
        )
        for start in range(0, len(values), 32):
            lines.append("  " + ", ".join(map(str, values[start : start + 32])) + ",")
        lines.extend(["};", ""])
    lines.extend(["#endif", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--case", choices=CASES, default="small")
    parser.add_argument(
        "--output", type=Path, default=ROOT / "tests/generated/p1_resnet_data.h"
    )
    args = parser.parse_args()
    tensors = reference(args.case)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(header(args.case, tensors), encoding="utf-8")
    expected = tensors["p1_expected"]
    print(
        f"Generated {args.output}: {args.case}, {len(expected)} values, range [{min(expected)}, {max(expected)}]"
    )


if __name__ == "__main__":
    main()
